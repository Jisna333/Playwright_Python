# Step 1: Create and write
print("Creating file...")
file = open("notes.txt", "w")
file.write("This is line 1\n")
file.write("This is line 2\n")
file.write("This is line 3\n")
file.write("This is line 4\n")
file.write("This is line 5\n")
file.close()
print("File created with 5 lines!")
# Step 2: Read complete file
print("\nReading complete file:")
file = open("notes.txt", "r")
content = file.read()
print(content)
file.close()
# Step 3: Read specific line (third line)
print("Third line only:")
file = open("notes.txt", "r")
lines = file.readlines()
print(lines[2])
file.close()
# Step 4: Append new line
print("Appending new line...")
file = open("notes.txt", "a")
file.write("This is line 6\n")
file.close()
print("Line appended!")

# Verify append worked
print("\nFile after append:")
file = open("notes.txt", "r")
content = file.read()
print(content)
file.close()